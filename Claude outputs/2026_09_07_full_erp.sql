-- ============================================================================
-- Brokole - the rest of the ERP schema
--
-- Run with:  php api/migrate.php
--
-- Everything the app needs a database for that didn't have one yet:
--   1. Subscriptions   plans, subscriptions, schedule, pauses, invoices
--   2. Recipes         the link between a menu item and its ingredients
--   3. Procurement     vendors, purchase orders, goods receipts, bills
--   4. Production      daily plan + kitchen tickets
--   5. Payments & tax  payments, refunds, tax rates, customer invoices
--   6. Delivery        zones, rider assignments
--   7. Nutrition       customer goals, macro targets, meal log
--
-- Conventions, same as the rest of the schema:
--   money  DECIMAL(12,2), never a float
--   ids    CHAR(36) UUIDs generated by the API
--   time   created_at / updated_at on everything, soft delete where it matters
--   stock  append-only ledgers; on-hand and cost are DERIVED, never stored
-- ============================================================================

SET NAMES utf8mb4;


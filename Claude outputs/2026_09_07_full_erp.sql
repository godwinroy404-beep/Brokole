-- ═══════════════════════════════════════════════════════════════════════════
-- 2 · RECIPES - the backbone
--
-- Right now a menu item's macros are typed in by hand and its cost is unknown.
-- Once recipe_lines exist, BOTH come from the same rows, so the nutrition label
-- on the storefront and the margin in the sales report can never disagree.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS recipes (
  id            CHAR(36)      NOT NULL PRIMARY KEY,
  menu_item_id  CHAR(36)      NOT NULL UNIQUE,
  yield_qty     DECIMAL(10,3) NOT NULL DEFAULT 1,     -- portions this makes
  method        TEXT          NULL,
  prep_minutes  SMALLINT UNSIGNED NULL,
  is_active     TINYINT(1)    NOT NULL DEFAULT 1,
  created_at    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT rec_item_fk FOREIGN KEY (menu_item_id) REFERENCES menu_items(id) ON DELETE CASCADE,
  CONSTRAINT rec_yield_chk CHECK (yield_qty > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS recipe_lines (
  id            CHAR(36)      NOT NULL PRIMARY KEY,
  recipe_id     CHAR(36)      NOT NULL,
  ingredient_id CHAR(36)      NOT NULL,
  -- Quantity in the ingredient's own unit, for ONE yield_qty batch.
  quantity      DECIMAL(12,4) NOT NULL,
  -- Trim/cooking loss. 0.9 means you buy 1kg and 900g reaches the bowl.
  yield_factor  DECIMAL(5,3)  NOT NULL DEFAULT 1.000,
  note          VARCHAR(255)  NULL,
  UNIQUE KEY rl_recipe_ing_uk (recipe_id, ingredient_id),
  CONSTRAINT rl_recipe_fk FOREIGN KEY (recipe_id)     REFERENCES recipes(id) ON DELETE CASCADE,
  CONSTRAINT rl_ing_fk    FOREIGN KEY (ingredient_id) REFERENCES ingredients(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Food cost per portion, derived. Never store this - the moment an ingredient
-- price changes, a stored copy is a lie.
CREATE OR REPLACE VIEW recipe_costs AS
SELECT
  r.menu_item_id,
  r.id AS recipe_id,
  ROUND(SUM(rl.quantity / NULLIF(rl.yield_factor, 0) * i.cost_per_unit) / NULLIF(r.yield_qty, 0), 2) AS food_cost_per_portion,
  COUNT(rl.id) AS ingredient_count
FROM recipes r
JOIN recipe_lines rl ON rl.recipe_id = r.id
JOIN ingredients  i  ON i.id = rl.ingredient_id
WHERE r.is_active = 1
GROUP BY r.id, r.menu_item_id, r.yield_qty;

-- Margin per menu item: price against derived food cost.
CREATE OR REPLACE VIEW menu_item_margins AS
SELECT
  mi.id AS menu_item_id, mi.slug, mi.name, mi.price,
  rc.food_cost_per_portion,
  ROUND(mi.price - COALESCE(rc.food_cost_per_portion, 0), 2) AS gross_margin,
  CASE WHEN mi.price > 0 AND rc.food_cost_per_portion IS NOT NULL
       THEN ROUND((mi.price - rc.food_cost_per_portion) / mi.price * 100, 1) END AS margin_pct
FROM menu_items mi
LEFT JOIN recipe_costs rc ON rc.menu_item_id = mi.id
WHERE mi.deleted_at IS NULL;

